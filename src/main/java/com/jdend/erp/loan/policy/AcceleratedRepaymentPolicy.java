package com.jdend.erp.loan.policy;

/**
 * 기한이익상실 이후 들어온 상환을 어떻게 처리할지.
 *
 * <p>기한이익상실을 등록하면 미래 회차가 '청구중지'로 바뀐다. 그런데 변제충당이
 * 청구중지 회차를 아예 제외하고 있어서, <b>잔여원금 전액을 청구해 놓고 정작
 * 그 원금을 갚을 수 없는</b> 상태였다. 입금이 이미 도래한 회차만 메우고 나머지는
 * 전부 선수금으로 남았다.
 *
 * <p>'청구를 중지한다'와 '변제를 받지 않는다'는 다른 이야기다. 기본값은 원금차감이다.
 * 다만 회사에 따라 상실 후 입금을 일단 선수금으로 잡아 두고 나중에 정리하는
 * 실무도 있어 선택할 수 있게 한다.
 */
public enum AcceleratedRepaymentPolicy {

  /**
   * 기본값. 청구중지 회차의 원금도 충당 대상에 넣는다.
   * 조기 변제기가 도래한 원금이므로 갚으면 그만큼 줄어드는 것이 맞다.
   *
   * <p>원금만 대상이다. 청구중지 회차의 <b>약정이자는 충당하지 않는다</b> —
   * 조기 상환된 구간의 이자는 애초에 발생하지 않았기 때문이다.
   */
  REDUCE_PRINCIPAL,

  /**
   * 도래한 회차만 충당하고 나머지는 선수금으로 둔다.
   * 상실 후 입금을 별도로 관리하고 싶을 때 쓴다.
   */
  HOLD_AS_PREPAID
}
